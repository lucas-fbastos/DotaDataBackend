package io.luck.AghsLabs.mapper;

import io.luck.AghsLabs.model.MatchPlayer;
import io.luck.AghsLabs.model.entity.Hero;
import io.luck.AghsLabs.model.entity.Item;
import io.luck.AghsLabs.providers.opendota.model.OpenDotaMatchPlayer;
import org.springframework.stereotype.Component;
import java.util.*;

@Component
public class MatchPlayerMapper {
    public Set<MatchPlayer> convert(Collection<OpenDotaMatchPlayer> source,
                                    Map<Long, Hero> heroesById, Map<Long, Item> itemsById) {
        Set<MatchPlayer> result = new LinkedHashSet<>();
        if (source == null) return result;
        for (var player : source) {
            result.add(MatchPlayer.builder()
                    .playerSlot(player.playerSlot())
                    .obsPlaced(player.obsPlaced())
                    .senPlaced(player.senPlaced())
                    .creepsStacked(player.creepsStacked())
                    .campsStacked(player.campsStacked())
                    .runePickups(player.runePickups())
                    .firstBloodClaimed(player.firstBloodClaimed())
                    .teamfightParticipation(player.teamfightParticipation())
                    .towersKilled(player.towersKilled())
                    .roshansKilled(player.roshansKilled())
                    .observersPlaced(player.observersPlaced())
                    .stuns(player.stuns())
                    .maxHeroHit(MatchDetailsDataMapper.convert(player.maxHeroHit()))
                    .times(player.times())
                    .goldT(player.goldT())
                    .lhT(player.lhT())
                    .dnT(player.dnT())
                    .xpT(player.xpT())
                    .netWorthT(player.netWorthT())
                    .campsStackedT(player.campsStackedT())
                    .towerDamageT(player.towerDamageT())
                    .heroDamageT(player.heroDamageT())
                    .heroHealingT(player.heroHealingT())
                    .purchaseLog(MatchDetailsDataMapper.mapList(player.purchaseLog(), MatchDetailsDataMapper::convert))
                    .killsLog(MatchDetailsDataMapper.mapList(player.killsLog(), MatchDetailsDataMapper::convert))
                    .deathsLog(MatchDetailsDataMapper.mapList(player.deathsLog(), MatchDetailsDataMapper::convert))
                    .buybackLog(MatchDetailsDataMapper.mapList(player.buybackLog(), MatchDetailsDataMapper::convert))
                    .runesLog(MatchDetailsDataMapper.mapList(player.runesLog(), MatchDetailsDataMapper::convert))
                    .actions(player.actions())
                    .pings(player.pings())
                    .purchase(player.purchase())
                    .goldReasons(player.goldReasons())
                    .xpReasons(player.xpReasons())
                    .killed(player.killed())
                    .itemUses(player.itemUses())
                    .abilityUses(player.abilityUses())
                    .abilityTargets(player.abilityTargets())
                    .damageTargets(player.damageTargets())
                    .heroHits(player.heroHits())
                    .damage(player.damage())
                    .damageTaken(player.damageTaken())
                    .damageInflictor(player.damageInflictor())
                    .runes(player.runes())
                    .killedBy(player.killedBy())
                    .killStreaks(player.killStreaks())
                    .multiKills(player.multiKills())
                    .lifeState(player.lifeState())
                    .healing(player.healing())
                    .damageInflictorReceived(player.damageInflictorReceived())
                    .randomed(player.randomed())
                    .predVict(player.predVict())
                    .neutralItemHistory(MatchDetailsDataMapper.mapList(player.neutralItemHistory(), MatchDetailsDataMapper::convert))
                    .accountId(player.accountId())
                    .partyId(player.partyId())
                    .permanentBuffs(MatchDetailsDataMapper.mapList(player.permanentBuffs(), MatchDetailsDataMapper::convert))
                    .partySize(player.partySize())
                    .teamNumber(player.teamNumber())
                    .teamSlot(player.teamSlot())
                    .heroId(player.heroId())
                    .heroVariant(player.heroVariant())
                    .item0(player.item0())
                    .item1(player.item1())
                    .item2(player.item2())
                    .item3(player.item3())
                    .item4(player.item4())
                    .item5(player.item5())
                    .backpack0(player.backpack0())
                    .backpack1(player.backpack1())
                    .backpack2(player.backpack2())
                    .itemNeutral(player.itemNeutral())
                    .itemNeutral2(player.itemNeutral2())
                    .kills(player.kills())
                    .deaths(player.deaths())
                    .assists(player.assists())
                    .leaverStatus(player.leaverStatus())
                    .lastHits(player.lastHits())
                    .denies(player.denies())
                    .goldPerMin(player.goldPerMin())
                    .xpPerMin(player.xpPerMin())
                    .level(player.level())
                    .netWorth(player.netWorth())
                    .aghanimsScepter(player.aghanimsScepter())
                    .aghanimsShard(player.aghanimsShard())
                    .moonshard(player.moonshard())
                    .heroDamage(player.heroDamage())
                    .towerDamage(player.towerDamage())
                    .heroHealing(player.heroHealing())
                    .gold(player.gold())
                    .goldSpent(player.goldSpent())
                    .personaName(player.personaName())
                    .name(player.name())
                    .lastLogin(player.lastLogin())
                    .rankTier(player.rankTier())
                    .computedMmr(player.computedMmr())
                    .isSubscriber(player.isSubscriber())
                    .radiantWin(player.radiantWin())
                    .startTime(player.startTime())
                    .duration(player.duration())
                    .cluster(player.cluster())
                    .lobbyType(player.lobbyType())
                    .gameMode(player.gameMode())
                    .isContributor(player.isContributor())
                    .patch(player.patch())
                    .region(player.region())
                    .isRadiant(player.isRadiant())
                    .win(player.win())
                    .lose(player.lose())
                    .totalGold(player.totalGold())
                    .totalXp(player.totalXp())
                    .killsPerMin(player.killsPerMin())
                    .kda(player.kda())
                    .abandons(player.abandons())
                    .neutralKills(player.neutralKills())
                    .towerKills(player.towerKills())
                    .courierKills(player.courierKills())
                    .laneKills(player.laneKills())
                    .heroKills(player.heroKills())
                    .observerKills(player.observerKills())
                    .sentryKills(player.sentryKills())
                    .roshanKills(player.roshanKills())
                    .necronomiconKills(player.necronomiconKills())
                    .ancientKills(player.ancientKills())
                    .buybackCount(player.buybackCount())
                    .observerUses(player.observerUses())
                    .sentryUses(player.sentryUses())
                    .laneEfficiency(player.laneEfficiency())
                    .laneEfficiencyPct(player.laneEfficiencyPct())
                    .lane(player.lane())
                    .laneRole(player.laneRole())
                    .isRoaming(player.isRoaming())
                    .purchaseTime(player.purchaseTime())
                    .purchaseTpscroll(player.purchaseTpscroll())
                    .actionsPerMin(player.actionsPerMin())
                    .lifeStateDead(player.lifeStateDead())
                    .benchmarks(MatchDetailsDataMapper.convert(player.benchmarks()))
                    .positionEst(player.positionEst())
                    .purchaseWardObserver(player.purchaseWardObserver())
                    .purchaseWardSentry(player.purchaseWardSentry())
                    .purchaseGem(player.purchaseGem())
                    .team(player.getTeam().name())
                    .abilityUpgrade(player.abilityUpgradesArr())
                    .tpsBought(player.purchaseTpscroll())
                    .heroHeal(player.heroHealing())
                    .hero(heroesById.get(player.heroId()))
                    .won(player.playerWon())
                    .rank(player.rankTier() == null ? null : player.rankTier().toString())
                    .items(player.getItems().stream().map(id -> id == null ? null : itemsById.get(id)).toList())
                    .backpackItemsId(Arrays.asList(player.backpack0(), player.backpack1(), player.backpack2()))
                    .build());
        }
        return result;
    }
}
